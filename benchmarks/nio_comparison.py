"""Every SwarmOpt algorithm at an equal evaluation budget.

Writes a Markdown table (default docs/nio_benchmarks.md). Each method gets
the same number of objective evaluations on each function, over several
seeds, through ``swarmopt.nio.compare``. The core global-best PSO runs
through ``Swarm`` with ``epochs`` chosen to spend the same budget.

    python benchmarks/nio_comparison.py --budget 5000 --dims 10 --seeds 3
"""

from __future__ import annotations

import argparse
import math
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


from swarmopt import Swarm  # noqa: E402
from swarmopt.nio.compare import compare  # noqa: E402
from swarmopt.nio.registry import FAMILY_NAMES  # noqa: E402


def sphere(x):
    return sum(v * v for v in x)


def rastrigin(x):
    return 10 * len(x) + sum(v * v - 10 * math.cos(2 * math.pi * v) for v in x)


def rosenbrock(x):
    return sum(100 * (x[i + 1] - x[i] ** 2) ** 2 + (1 - x[i]) ** 2 for i in range(len(x) - 1))


def ackley(x):
    n = len(x)
    a = -20 * math.exp(-0.2 * math.sqrt(sum(v * v for v in x) / n))
    b = -math.exp(sum(math.cos(2 * math.pi * v) for v in x) / n)
    return a + b + 20 + math.e


OBJECTIVES = {"sphere": sphere, "rastrigin": rastrigin, "rosenbrock": rosenbrock, "ackley": ackley}


def core_pso(objective, dims, budget, seeds, population):
    epochs = max(1, budget // population - 1)
    values = []
    for seed in seeds:
        swarm = Swarm(n_particles=population, dims=dims, c1=2.0, c2=2.0, w=0.9,
                      epochs=epochs, obj_func=lambda p: objective(list(p)),
                      algo="global", velocity_clamp=(-5.0, 5.0), seed=seed)
        swarm.optimize()
        values.append(float(swarm.best_cost))
    return statistics.median(values), min(values), max(values)


def fmt(value):
    if value == 0:
        return "0"
    if abs(value) >= 1e4 or abs(value) < 1e-3:
        return f"{value:.2e}"
    return f"{value:.3f}"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--budget", type=int, default=5000)
    parser.add_argument("--dims", type=int, default=10)
    parser.add_argument("--seeds", type=int, default=3)
    parser.add_argument("--population", type=int, default=30)
    parser.add_argument("--out", default=str(ROOT / "docs" / "nio_benchmarks.md"))
    args = parser.parse_args()

    seeds = list(range(args.seeds))
    bounds = [(-5.0, 5.0)] * args.dims
    start = time.time()
    results = compare(OBJECTIVES, bounds, args.budget, seeds=seeds,
                      population_size=args.population)
    table = {}
    for r in results:
        table.setdefault((r.family, r.name), {})[r.objective] = r
    elapsed = time.time() - start

    labels = list(OBJECTIVES)
    lines = [
        "# Every algorithm at an equal evaluation budget",
        "",
        f"Each method had {args.budget} objective evaluations on each function in "
        f"{args.dims} dimensions, bounds [-5, 5], population {args.population}, "
        f"seeds {seeds}. Values are the median best value found (lower is better; "
        "every function's minimum is 0). Generated by `benchmarks/nio_comparison.py`.",
        "",
        "These are default parameters on four classic functions. They say how each "
        "method behaves out of the box at this budget, not which method is best in "
        "general. Rank within a column, not across columns.",
        "",
        "| family | algo | " + " | ".join(labels) + " |",
        "|---|---|" + "---|" * len(labels),
    ]
    core = [core_pso(OBJECTIVES[k], args.dims, args.budget, seeds, args.population) for k in labels]
    lines.append("| swarm | global (core PSO) | " + " | ".join(fmt(c[0]) for c in core) + " |")
    for fam in FAMILY_NAMES:
        for (family, name), row in sorted(table.items()):
            if family != fam:
                continue
            lines.append(f"| {family} | {name} | " + " | ".join(fmt(row[k].median) for k in labels) + " |")
    lines += ["", f"Run time: {elapsed:.0f} s.", ""]
    Path(args.out).write_text("\n".join(lines))
    print(f"wrote {args.out} in {elapsed:.0f} s")


if __name__ == "__main__":
    main()
